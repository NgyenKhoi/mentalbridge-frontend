import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const names = [
  'handshake-v1',
  'command-envelope-v1',
  'acknowledgement-v1',
  'error-v1',
  'server-event-v1',
]
const exports = [
  'handshakeV1Schema',
  'commandEnvelopeV1Schema',
  'acknowledgementV1Schema',
  'errorV1Schema',
  'serverEventV1Schema',
]
const schemas = await Promise.all(
  names.map((name) =>
    readFile(
      resolve(root, 'contracts/realtime', `${name}.schema.json`),
      'utf8',
    ).then(JSON.parse),
  ),
)
const target = resolve(root, 'lib/realtime/contracts.generated.ts')
const prettierConfig = (await resolveConfig(target)) ?? {}

const generated = await format(
  `/* This file is generated by scripts/generate-realtime-contracts.mjs. Do not edit. */\nimport type { FromSchema } from 'json-schema-to-ts'\n\n${schemas.map((schema, index) => `export const ${exports[index]} = ${JSON.stringify(schema, null, 2)} as const\n`).join('\n')}\nexport type HandshakeV1 = FromSchema<typeof handshakeV1Schema>\nexport type CommandEnvelopeV1 = FromSchema<typeof commandEnvelopeV1Schema>\nexport type AcknowledgementV1 = FromSchema<typeof acknowledgementV1Schema>\nexport type SafeErrorV1 = FromSchema<typeof errorV1Schema>\nexport type ServerEventV1 = FromSchema<typeof serverEventV1Schema>\n`,
  { ...prettierConfig, parser: 'typescript' },
)

if (process.argv.includes('--provider-check')) {
  const providerDirectory = process.env.REALTIME_CONTRACT_SOURCE
    ? resolve(process.env.REALTIME_CONTRACT_SOURCE)
    : resolve(
        root,
        '../../../backend/mentalbridge-backend/contracts/websocket/realtime',
      )
  let drifted = false
  for (let index = 0; index < names.length; index += 1) {
    const provider = await readFile(
      resolve(providerDirectory, `${names[index]}.schema.json`),
      'utf8',
    )
      .then(JSON.parse)
      .catch(() => undefined)
    if (JSON.stringify(provider) !== JSON.stringify(schemas[index])) {
      console.error(
        `${names[index]}.schema.json differs from the Realtime provider contract.`,
      )
      drifted = true
    }
  }
  if (drifted) process.exitCode = 1
  else
    console.log(
      'Frontend realtime v1 schemas match the Realtime provider schemas.',
    )
} else if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  const normalizeEndOfLine = (value) => value.replace(/\r\n/g, '\n')
  if (normalizeEndOfLine(current) !== normalizeEndOfLine(generated)) {
    console.error(
      'Realtime generated contracts are stale. Run npm run contract:generate.',
    )
    process.exitCode = 1
  } else {
    console.log(
      'Realtime generated contracts match the checked-in v1 JSON Schemas.',
    )
  }
} else {
  await writeFile(target, generated)
  console.log('Generated lib/realtime/contracts.generated.ts')
}
