// The variation catalogue of the Mầm orchestrator (MB-896, docs/ADR_MAM_RIVE_V2_CONTRACT.md "Orchestrator"): which
// looks an intent can take, where they may play, and what each one does, step by step. Existing behaviours keep their
// timing (`celebrate_soft`, `nod`, the idle actions, the welcome airplane); the new ones need the v0.8 asset
// (`minAsset: 'v08'`) or draw a host prop. Tiers bound length: micro up to 2 s, expressive up to 5 s, cinematic 5 to 9 s.
import { MAM_ONE_SHOT_MS, type MamLoopingBehavior } from './mam-contract'
import type { MamStep, MamVariation } from './mam-orchestrator'
import { BUTTERFLY_MS, butterflyAt, gazeToward } from './mam-scenes'

export const TIER_MAX_MS = {
  micro: 2000,
  expressive: 5000,
  cinematic: 9000,
} as const
export const CINEMATIC_MIN_MS = 5000

const BOTH = ['full', 'quiet'] as const
const FULL = ['full'] as const

/** One one-shot, as long as the asset plays it. */
const shot = (kind: keyof typeof MAM_ONE_SHOT_MS): readonly MamStep[] => [
  { at: 0, oneShot: kind },
]
const loop = (behavior: MamLoopingBehavior): readonly MamStep[] => [
  { at: 0, loop: behavior },
]

/** The butterfly's wander as gaze steps every 300 ms, so Mầm's eyes follow what is drawn. */
const butterflyGaze: readonly MamStep[] = Array.from(
  { length: Math.ceil(BUTTERFLY_MS / 300) },
  (_, i) => ({
    at: i * 300,
    gaze: gazeToward(butterflyAt((i * 300) / BUTTERFLY_MS).x),
  }),
)

